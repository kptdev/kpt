const (
	FuncGenPkgContext = "builtins/gen-pkg-context"
	GHCRImagePrefix   = "ghcr.io/kptdev/krm-functions-catalog"
	PrefixEnvVar      = "KPT_IMAGE_PREFIX"
)

// DefaultImagePrefix returns the image prefix from the KPT_IMAGE_PREFIX env var, or GHCRImagePrefix if unset.
func DefaultImagePrefix() string {
	if p := os.Getenv(PrefixEnvVar); p != "" {
		return p
	}
	return GHCRImagePrefix
}

// ConditionEvaluator evaluates a function celCondition against the current resource list.
type ConditionEvaluator interface {
	EvaluateCondition(ctx context.Context, celCond string, resources []*yaml.RNode, checkFrequency uint, costLimit uint64) (bool, error)
}

type RunnerOptions struct {
	// ImagePullPolicy controls the image pulling behavior before running the container.
	ImagePullPolicy ImagePullPolicy

	// when set to true, function runner will set the package path annotation
	// on resources that do not have it set. The resources generated by
	// functions do not have this annotation set.
	SetPkgPathAnnotation bool

	DisplayResourceCount bool

	// allowExec determines if function binary executable are allowed
	// to be run during pipeline execution. Running function binaries is a
	// privileged operation, so explicit permission is required.
	AllowExec bool

	// AllowNetwork specifies if container based functions are allowed
	// to access network during pipeline execution. Accessing network is
	// considered a privileged operation (and makes render operation non-hermetic),
	// so explicit permission is desired.
	AllowNetwork bool

	// allowWasm determines if function wasm are allowed to be run during pipeline
	// execution. Running wasm function is an alpha feature, so it needs to be
	// enabled explicitly.
	AllowWasm bool

	// ImagePrefix determines the prefix ResolveToImage will use when resolving a
	// partial image reference to a fully qualified image reference
	ImagePrefix string

	LogOptions LogOptions

	// FullDisplayName is the resolved display name of the package or subpackage.
	// Meant for internal usage, like the render executor.
	FullDisplayName string

	// CELEnvironment evaluates function conditions. It is nil until
	// InitCELEnvironment in the root module has been called successfully.
	// Assign only a non-nil implementation: a typed nil stored in this
	// interface is not a nil interface.
	CELEnvironment ConditionEvaluator

	// CelCheckFrequency is the number of CEL evaluation steps before an interruption is checked.
	CelCheckFrequency uint

	// CelCostLimit is the maximum cost of a CEL evaluation.
	CelCostLimit uint64

	ExtraTlsCerts [][]byte

	// Timeout is the maximum time the whole run is allowed to take: all the
	// functions of the pipeline for `kpt fn render`, and the function for
	// `kpt fn eval`. A container or exec function that is still running when
	// it has passed is killed. When it is zero, there is no limit for the
	// whole run, and each function is limited by the default timeout of the
	// function runtime (5 minutes).
	Timeout time.Duration
}

type PackageIDType int8

const (
	// Use directory name to identify the package/subpackage
	DirName PackageIDType = iota
	// Use Kptfile metadata.name to identify the package/subpackage
	KptfileMeta
)

type LogOptions struct {
	PkgNameFormat string
	PkgNameSep    string
	PkgNameID     PackageIDType

	// TruncateImageName determines whether the full image name or just the base
	// name and the tag will be logged.
	TruncateImageName bool

	// ResultSeparator is used to join the per-item lines of a function's
	// structured [Results] output. Defaults to "\n" (multi-line) when empty.
	// Embedding applications (e.g. Porch) can set this to "; " to keep the
	// result output on a single line for log-friendliness.
	ResultSeparator string
}

func (o *LogOptions) IsZero() bool {
	return o.PkgNameFormat == "" && o.PkgNameSep == "" && o.PkgNameID == 0 && !o.TruncateImageName && o.ResultSeparator == ""
}

func (o *LogOptions) FillDefaults() {
	defaults := DefaultLogOptions()
	if o.PkgNameFormat == "" {
		o.PkgNameFormat = defaults.PkgNameFormat
	}
	if o.PkgNameSep == "" {
		o.PkgNameSep = defaults.PkgNameSep
	}
}

func DefaultLogOptions() LogOptions {
	return LogOptions{
		PkgNameFormat: "%s",
		PkgNameSep:    "/",
		PkgNameID:     DirName,

		TruncateImageName: false,
	}
}

